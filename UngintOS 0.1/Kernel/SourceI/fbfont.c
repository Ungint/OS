static void fbfont_pixel(
    uint32_t *buffer,
    uint32_t width,
    uint32_t height,
    uint32_t pitch,
    uint32_t x,
    uint32_t y,
    uint32_t color
)
{
    if(!buffer)
        return;

    if(x >= width || y >= height)
        return;

    buffer[y * (pitch / 4) + x] = color;
}

void fbfont_draw_char(
    uint32_t *buffer,
    uint32_t width,
    uint32_t height,
    uint32_t pitch,
    uint32_t x,
    uint32_t y,
    char c,
    uint32_t fg,
    uint32_t bg
)
{
    if(!buffer)
        return;

    uint8_t ch = (uint8_t)c;

    if(ch >= 128)
        ch = '?';

    for(uint32_t yy = 0; yy < 16; yy++)
    {
        uint8_t bits = font8x16[ch][yy];

        for(uint32_t xx = 0; xx < 8; xx++)
        {
            if(bits & (0x80 >> xx))
            {
                fbfont_pixel(
                    buffer,
                    width,
                    height,
                    pitch,
                    x + xx,
                    y + yy,
                    fg
                );
            }
            else if(bg != 0xFFFFFFFF)
            {
                fbfont_pixel(
                    buffer,
                    width,
                    height,
                    pitch,
                    x + xx,
                    y + yy,
                    bg
                );
            }
        }
    }
}

void fbfont_draw_string(
    uint32_t *buffer,
    uint32_t width,
    uint32_t height,
    uint32_t pitch,
    uint32_t x,
    uint32_t y,
    const char *str,
    uint32_t fg,
    uint32_t bg
)
{
    if(!buffer || !str)
        return;

    while(*str)
    {
        if(*str == '\n')
        {
            x = 0;
            y += 16;

            if(y >= height)
                break;

            str++;
            continue;
        }

        fbfont_draw_char(
            buffer,
            width,
            height,
            pitch,
            x,
            y,
            *str,
            fg,
            bg
        );

        x += 8;

        if(x + 8 > width)
        {
            x = 0;
            y += 16;
        }

        if(y + 16 > height)
            break;

        str++;
    }
}