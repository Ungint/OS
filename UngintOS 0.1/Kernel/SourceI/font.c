static uint8_t custom_glyph_data[FONT_MAX_GLYPHS * FONT_MAX_HEIGHT];
static uint8_t active_glyph_w = 8;
static uint8_t active_glyph_h = 16;
static uint8_t active_first_char = 32;
static uint16_t active_count = 95;
static int using_custom = 0;

void font_init(void) {
    using_custom = 0;
    active_glyph_w = 8;
    active_glyph_h = 16;
    active_first_char = 32;
    active_count = 95;
}

uint8_t font_glyph_w(void) { return active_glyph_w; }
uint8_t font_glyph_h(void) { return active_glyph_h; }

static int ends_with_dot_f(const char *name) {
    int len = strlen(name);
    if (len < 2) return 0;
    char c1 = name[len - 2];
    char c2 = name[len - 1];
    if (c1 != '.') return 0;
    return (c2 == 'f' || c2 == 'F');
}

int font_load(const char *path) {
    if (fat32_open(path) != 0) {
        return -1;
    }

    font_header_t hdr;
    int n = fat32_read(&hdr, sizeof(hdr));
    if (n != (int)sizeof(hdr)) {
        fat32_close();
        return -1;
    }

    if (hdr.magic[0] != 'M' || hdr.magic[1] != 'F' ||
        hdr.magic[2] != 'N' || hdr.magic[3] != 'T') {
        fat32_close();
        return -1;
    }

    if (hdr.glyph_w == 0 || hdr.glyph_w > 8) { fat32_close(); return -1; }
    if (hdr.glyph_h == 0 || hdr.glyph_h > FONT_MAX_HEIGHT) { fat32_close(); return -1; }
    if (hdr.count == 0) { fat32_close(); return -1; }

    uint32_t data_size = (uint32_t)hdr.count * (uint32_t)hdr.glyph_h;
    if (data_size > sizeof(custom_glyph_data)) {
        fat32_close();
        return -1;
    }

    int read_n = fat32_read(custom_glyph_data, data_size);
    fat32_close();

    if (read_n != (int)data_size) {
        return -1;
    }

    active_glyph_w = hdr.glyph_w;
    active_glyph_h = hdr.glyph_h;
    active_first_char = hdr.first_char;
    active_count = hdr.count;
    using_custom = 1;

    return 0;
}

int font_autoload(void) {
    static char names[32][64];
    int is_dir[32];

    int n = fat32_list_dir(FONT_DIR, &names[0][0], 64, is_dir, NULL, 32);
    if (n <= 0) return -1;

    for (int i = 0; i < n; i++) {
        if (is_dir[i]) continue;
        if (!ends_with_dot_f(names[i])) continue;

        char full_path[128];
        strcpy(full_path, FONT_DIR);
        strcat(full_path, "/");
        strcat(full_path, names[i]);

        if (font_load(full_path) == 0) {
            return 0;
        }
    }

    return -1;
}

void font_draw_char(uint32_t x,uint32_t y,char c,uint32_t fg,uint32_t bg)
{
    uint32_t *buffer;
    uint32_t width;
    const uint8_t *rows;
    uint8_t w = active_glyph_w;
    uint8_t h = active_glyph_h;

    if(!gfx_ready())
        return;

    buffer = gfx_get_backbuffer();
    width = gfx_width();

    if(!buffer)
        return;

    if(!using_custom)
    {
        if(c < 32 || c > 126)
            c = '?';
        rows = builtin_font_8x16[(int)(c - 32)];
    }
    else
    {
        int idx = (unsigned char)c - active_first_char;
        if(idx < 0 || idx >= active_count)
            idx = 0;
        rows = &custom_glyph_data[(uint32_t)idx * h];
    }

    for(int row = 0;row < h;row++)
    {
        uint8_t line = rows[row];
        uint32_t *dst = buffer + (y + row) * width + x;

        for(int col = 0;col < w;col++)
        {
            if(line & (1 << (7 - col)))
                dst[col] = fg;
            else if(bg != GFX_TRANSPARENT)
                dst[col] = bg;
        }
    }
}

void font_draw_string(uint32_t x, uint32_t y, const char *str, uint32_t fg, uint32_t bg) {
    uint32_t start_x = x;
    while (*str) {
        if (*str == '\n') {
            x = start_x;
            y += active_glyph_h;
            str++;
            continue;
        }
        font_draw_char(x, y, *str, fg, bg);
        x += active_glyph_w;
        str++;
    }
}

void font_draw_string_canvas(int canvas_id, int x, int y, const char *str, uint32_t fg, uint32_t bg) {
    uint8_t w = active_glyph_w;
    uint8_t h = active_glyph_h;
    int start_x = x;

    while (*str) {
        char c = *str;
        if (c == '\n') {
            x = start_x;
            y += h;
            str++;
            continue;
        }

        const uint8_t *rows;
        if (!using_custom) {
            if (c < 32 || c > 126) c = '?';
            rows = builtin_font_8x16[(int)(c - 32)];
        } else {
            int idx = (unsigned char)c - active_first_char;
            if (idx < 0 || idx >= active_count) idx = 0;
            rows = &custom_glyph_data[(uint32_t)idx * h];
        }

        for (int row = 0; row < h; row++) {
            uint8_t line = rows[row];
            for (int col = 0; col < w; col++) {
                if (line & (1 << (7 - col))) {
                    canvas_put_pixel(canvas_id, x + col, y + row, fg);
                } else if (bg != GFX_TRANSPARENT) {
                    canvas_put_pixel(canvas_id, x + col, y + row, bg);
                }
            }
        }

        x += w;
        str++;
    }
}
